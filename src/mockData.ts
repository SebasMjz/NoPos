function makeSaleItems(products: { product: typeof mockProducts[0]; qty: number }[]): SaleItem[] {
  return products.map(({ product, qty }) => ({
    productId: product.id,
    name: product.name,
    sku: product.sku,
    price: product.price,
    quantity: qty,
    subtotal: product.price * qty,
  }));
}

function buildSale(
  folio: string,
  customer: typeof mockCustomers[0] | null,
  cashier: typeof mockUsers[0],
  items: SaleItem[],
  paymentMethod: Sale['paymentMethod'],
  documentType: Sale['documentType'],
  status: Sale['status'],
  daysAgo: number,
  discount = 0,
): Sale {
  const subtotal = items.reduce((s, i) => s + i.subtotal, 0);
  const tax = documentType === 'Factura' ? (subtotal - discount) * 0.13 : 0;
  const total = subtotal - discount + tax;
  const date = new Date();
  date.setDate(date.getDate() - daysAgo);
  return {
    id: `s${folio}`,
    folio: `V-${folio}`,
    documentType,
    customerId: customer?.id ?? null,
    customerName: customer?.name ?? 'Cliente General',
    cashierId: cashier.id,
    cashierName: cashier.name,
    items,
    subtotal,
    tax,
    discount,
    total,
    paymentMethod,
    status,
    createdAt: date.toISOString(),
  };
}

